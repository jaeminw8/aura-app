-- 005: AI conversation starters. Adds chat_suggestions: the 3 openers the AI step writes for a new
-- match chat (used_at = when someone sent a message that started from that one).
-- Adds to an existing aura database WITHOUT wiping it, so it's safe on the shared Find Friends App
-- database. db/schema.sql already includes it for fresh builds.
-- Safe to re-run. Apply with: npm run db:migrate (before deploying the API that uses it).

BEGIN;

-- Create the table as whichever role owns aura's other tables (aura_app on Find Friends App), even
-- when this is run with the postgres login. A table owned by anyone else would be closed to the
-- API (RLS is on with no policies, and only the owner gets past that) and would make the next
-- db:reset fail, because only the owner can drop it. SET LOCAL lasts until COMMIT.
DO $$
DECLARE
  app_owner name := (SELECT tableowner FROM pg_tables WHERE schemaname = 'public' AND tablename = 'chats');
BEGIN
  IF app_owner <> current_user THEN
    EXECUTE format('SET LOCAL ROLE %I', app_owner);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS chat_suggestions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id     bigint       NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
  text        varchar(120) NOT NULL CHECK (btrim(text) <> ''),
  used_at     timestamptz,
  created_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS chat_suggestions_chat_idx ON chat_suggestions (chat_id);

-- Like every other table: RLS on with no policies keeps Supabase's auto-generated REST API closed.
ALTER TABLE chat_suggestions ENABLE ROW LEVEL SECURITY;

COMMIT;
