-- 001: OKR groundwork (meetups table + okr_metrics view).
-- Adds to an existing aura database WITHOUT wiping it, so it's safe on the shared
-- Find Friends App database. db/schema.sql already includes all of this for fresh builds.
-- Safe to re-run. Apply with: npm run db:migrate
-- Applied to Find Friends App on 2026-11-03.

BEGIN;

-- A matched pair of groups met up in person (KR4). One row per confirmed meetup;
-- a match can have several. Kept when the confirming user is deleted.
CREATE TABLE IF NOT EXISTS meetups (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id              bigint      NOT NULL REFERENCES group_matches(id) ON DELETE CASCADE,
  confirmed_by_user_id  bigint      REFERENCES users(id) ON DELETE SET NULL,
  created_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS meetups_match_idx ON meetups (match_id);
ALTER TABLE meetups ENABLE ROW LEVEL SECURITY;

-- Objective key results, computed live from the tables (one row, percentages 0-100).
--   KR1 connect_pct:   registered groups that matched with at least one other group
--   KR2 four_plus_pct: registered groups with 4 or more members
--   KR3 message_pct:   connected groups with a match chat where BOTH groups sent a message
--   KR4 meetup_pct:    connected groups with at least one confirmed meetup
-- A message counts toward its sender's group via chat_participants.group_id.
CREATE OR REPLACE VIEW okr_metrics WITH (security_invoker = true) AS
WITH match_sides AS (
  SELECT id AS match_id, group_low_id AS group_id FROM group_matches
  UNION ALL
  SELECT id, group_high_id FROM group_matches
),
sending_sides AS (
  SELECT DISTINCT c.match_id, cp.group_id
  FROM messages m
  JOIN chats c              ON c.id = m.chat_id
  JOIN chat_participants cp ON cp.chat_id = m.chat_id AND cp.user_id = m.sender_user_id
),
exchanged_matches AS (
  SELECT match_id FROM sending_sides GROUP BY match_id HAVING count(*) = 2
),
counts AS (
  SELECT
    (SELECT count(*) FROM friend_groups)                                   AS total_groups,
    (SELECT count(DISTINCT group_id) FROM match_sides)                     AS connected_groups,
    (SELECT count(*) FROM (SELECT group_id FROM group_memberships
                           GROUP BY group_id HAVING count(*) >= 4) g)      AS four_plus_groups,
    (SELECT count(DISTINCT ms.group_id) FROM match_sides ms
       JOIN exchanged_matches e USING (match_id))                         AS messaging_groups,
    (SELECT count(DISTINCT ms.group_id) FROM match_sides ms
       JOIN meetups mu USING (match_id))                                   AS meetup_groups
)
SELECT total_groups, connected_groups, four_plus_groups, messaging_groups, meetup_groups,
       round(100.0 * connected_groups / nullif(total_groups, 0), 1)     AS kr1_connect_pct,
       round(100.0 * four_plus_groups / nullif(total_groups, 0), 1)     AS kr2_four_plus_pct,
       round(100.0 * messaging_groups / nullif(connected_groups, 0), 1) AS kr3_message_pct,
       round(100.0 * meetup_groups    / nullif(connected_groups, 0), 1) AS kr4_meetup_pct
FROM counts;

COMMIT;
